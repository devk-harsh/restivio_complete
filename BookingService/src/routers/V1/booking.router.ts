import { Router } from 'express';
import { authenticate } from '../../middlewares/auth.middleware';
import { createBookingHandler, getBookingByIdHandler, listBookingsHandler, cancelBookingHandler } from '../../controllers/booking.controller';
import { validateRequestParams } from '../../validators';
import { cancelBookingParamsSchema } from '../../validators/booking.validator';
const router = Router();
router.use(authenticate);
router.post('/', createBookingHandler);
router.get('/', listBookingsHandler);
router.get('/:id', validateRequestParams(cancelBookingParamsSchema), getBookingByIdHandler);
router.post('/:id/cancel', validateRequestParams(cancelBookingParamsSchema), cancelBookingHandler);
export default router;
